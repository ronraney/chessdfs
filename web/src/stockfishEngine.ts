// The real `BlackEngine` (see engine/blackEngine.ts): Stockfish, compiled to
// WASM, run in a dedicated Web Worker so Black's out-of-book move never
// blocks the UI thread. Deliberately NOT under engine/ -- that directory's
// own rule (see engine/index.ts) is "no DOM, no I/O," and spinning up a
// Worker is squarely both; this is the one file allowed to do it, wired in
// explicitly by BuildScreen.tsx rather than defaulted to inside build.ts.
//
// Uses the "stockfish" npm package (added by this task) -- specifically its
// classical (pre-NNUE) 11.0.0 release: the engine only ever needs a quick,
// shallow read to sanity-check and rank a handful of candidate moves here,
// not peak playing strength, and 11.0.0's build is ~9MB unpacked versus
// 180MB+ for any NNUE-era release (16.0.0 on), which bundles multi-megabyte
// neural net weights the stronger search doesn't buy anything for this use.
// `scripts/sync-stockfish.mjs` copies its two runtime files (stockfish.js,
// stockfish.wasm) from node_modules into public/stockfish/ (gitignored,
// regenerated by `npm run sync-stockfish`, wired into dev/build/test -- see
// package.json) so they're served at a fixed, bundler-independent URL;
// `stockfish.js` is a classic (non-ES-module) Emscripten-generated worker
// script that locates its own .wasm file relative to its own URL, which is
// why both files need to sit next to each other under public/ rather than
// going through Vite's normal module graph.
import type { Square } from "chess.js";
import type { BlackEngine, EngineCandidate } from "./engine/blackEngine";
import type { ChessMove } from "./engine/rules";

const STOCKFISH_WORKER_URL = "/stockfish/stockfish.js";

// A UCI "go" that never returns (a worker that silently wedges, a build
// that never emits "bestmove") would otherwise hang Black's turn forever;
// this is just a safety margin over the caller's own movetime budget, not
// part of the engine's quick-setting target itself.
const RESPONSE_TIMEOUT_MARGIN_MS = 2000;

// Bug fix: a worker that loads but never reaches "uciok" -- e.g. its own
// WebAssembly.instantiate() fails (a bad .wasm fetch, same failure mode as
// the one that prompted this fix) in a way that doesn't bubble up as the
// Worker's global "error" event -- used to hang getReadyWorker() (and
// therefore every future analyze() call, since the rejected/never-settled
// promise is memoized) forever, which hung Black's whole turn. This bounds
// the readiness handshake the same way RESPONSE_TIMEOUT_MARGIN_MS already
// bounds an actual "go" search below, so getReadyWorker() always settles
// one way or the other.
const READY_TIMEOUT_MS = 10_000;

// UCI reports a forced mate as "score mate N" (N plies/moves to deliver it,
// negative if the side to move is the one getting mated) instead of a
// centipawn number. Folded into the same cp scale here, far outside any
// realistic positional eval, so chooseAmongSound's window logic needs no
// separate case for it: a mate FOR Black always beats every non-mate
// candidate, a mate AGAINST Black always loses to every non-mate candidate,
// and among same-sign mates, the sooner one still scores higher/lower.
const MATE_CP_MAGNITUDE = 100_000;

function mateToCp(mateIn: number): number {
  return mateIn >= 0 ? MATE_CP_MAGNITUDE - mateIn : -MATE_CP_MAGNITUDE - mateIn;
}

function parseUciMove(uci: string): ChessMove {
  return {
    from: uci.slice(0, 2) as Square,
    to: uci.slice(2, 4) as Square,
    promotion: uci.length > 4 ? uci.slice(4) : undefined,
  };
}

// One "info ... multipv N ... score cp X|mate Y ... pv <move> ..." line ->
// that multipv slot's current candidate, or null if the line isn't a
// multipv/score/pv info line at all (engine chatter: depth-only updates,
// "info string ...", etc.).
function parseInfoLine(line: string): { multipv: number; candidate: EngineCandidate } | null {
  const tokens = line.split(/\s+/);
  const multipvAt = tokens.indexOf("multipv");
  const scoreAt = tokens.indexOf("score");
  const pvAt = tokens.indexOf("pv");
  if (multipvAt === -1 || scoreAt === -1 || pvAt === -1) return null;

  const multipv = Number(tokens[multipvAt + 1]);
  const scoreKind = tokens[scoreAt + 1];
  const scoreValue = Number(tokens[scoreAt + 2]);
  if (!Number.isFinite(multipv) || !Number.isFinite(scoreValue)) return null;
  const cp = scoreKind === "mate" ? mateToCp(scoreValue) : scoreValue;

  const uciMove = tokens[pvAt + 1];
  if (!uciMove || uciMove.length < 4) return null;

  return { multipv, candidate: { move: parseUciMove(uciMove), cp } };
}

export class StockfishEngine implements BlackEngine {
  private readyPromise: Promise<Worker> | null = null;
  // Serializes calls through one worker -- Black only ever asks for one
  // move at a time, but this keeps overlapping requests (if they ever
  // happened) from racing each other's "info"/"bestmove" messages.
  private queue: Promise<unknown> = Promise.resolve();

  private getReadyWorker(): Promise<Worker> {
    if (this.readyPromise !== null) return this.readyPromise;
    this.readyPromise = new Promise<Worker>((resolve, reject) => {
      const worker = new Worker(STOCKFISH_WORKER_URL);
      const timeoutId = setTimeout(() => {
        worker.removeEventListener("message", onMessage);
        worker.terminate();
        reject(new Error(`stockfish worker never became ready (no "uciok" within ${READY_TIMEOUT_MS}ms)`));
      }, READY_TIMEOUT_MS);
      function onMessage(event: MessageEvent<unknown>): void {
        if (typeof event.data === "string" && event.data.includes("uciok")) {
          clearTimeout(timeoutId);
          worker.removeEventListener("message", onMessage);
          resolve(worker);
        }
      }
      worker.addEventListener("message", onMessage);
      worker.addEventListener("error", (event) => {
        clearTimeout(timeoutId);
        reject(event.error ?? new Error("stockfish worker failed to start"));
      });
      worker.postMessage("uci");
    });
    return this.readyPromise;
  }

  async analyze(fen: string, multiPv: number, moveTimeMs: number): Promise<EngineCandidate[]> {
    const run = this.queue.then(() => this.runOnce(fen, multiPv, moveTimeMs));
    this.queue = run.catch(() => undefined);
    return run;
  }

  private async runOnce(fen: string, multiPv: number, moveTimeMs: number): Promise<EngineCandidate[]> {
    const worker = await this.getReadyWorker();
    return new Promise<EngineCandidate[]>((resolve, reject) => {
      const byMultipv = new Map<number, EngineCandidate>();

      const timeoutId = setTimeout(() => {
        worker.removeEventListener("message", onMessage);
        reject(new Error("stockfish analysis timed out"));
      }, moveTimeMs + RESPONSE_TIMEOUT_MARGIN_MS);

      function onMessage(event: MessageEvent<unknown>): void {
        if (typeof event.data !== "string") return;
        const line = event.data;
        if (line.startsWith("info") && line.includes(" pv ")) {
          const parsed = parseInfoLine(line);
          if (parsed !== null) byMultipv.set(parsed.multipv, parsed.candidate);
        } else if (line.startsWith("bestmove")) {
          clearTimeout(timeoutId);
          worker.removeEventListener("message", onMessage);
          const candidates = [...byMultipv.entries()].sort(([a], [b]) => a - b).map(([, candidate]) => candidate);
          resolve(candidates);
        }
      }

      worker.addEventListener("message", onMessage);
      worker.postMessage(`setoption name MultiPV value ${multiPv}`);
      worker.postMessage(`position fen ${fen}`);
      worker.postMessage(`go movetime ${moveTimeMs}`);
    });
  }
}

export const stockfishEngine: BlackEngine = new StockfishEngine();
